/**
 * PIM Sector Definitions
 * Each sector defines the catalogs, product types, and attribute templates
 * available for that industry vertical.
 *
 * Every product type includes comprehensive, real-world attributes:
 * - Fashion: regional sizing (EU/US/UK), fabric GSM, care labels, gender
 * - Home: materials, textures, coatings, heat resistance, dimensions
 * - Electronics: full specs, connectivity, power
 * - Food: nutrition, allergens, certifications
 * - Industrial: compliance, safety, tolerances
 * - Beauty: ingredients, skin compatibility, certifications
 */

export type AttributeType =
  | "TEXT"
  | "NUMBER"
  | "BOOLEAN"
  | "SELECT"
  | "MULTISELECT"
  | "DATE"
  | "RICH_TEXT"
  | "URL"
  | "COLOR";

export type Sector =
  | "ELECTRONICS"
  | "FASHION"
  | "FOOD"
  | "INDUSTRIAL"
  | "HOME"
  | "BEAUTY"
  | "AUTOMOTIVE";

export interface AttributeTemplate {
  name: string;
  slug: string;
  type: AttributeType;
  unit?: string;
  isRequired?: boolean;
  isFilterable?: boolean;
  isSearchable?: boolean;
  showOnCard?: boolean;
  options?: string[];
  validation?: { min?: number; max?: number; pattern?: string };
  group: string;
}

export interface ProductTypeTemplate {
  name: string;
  slug: string;
  description: string;
  icon?: string;
  attributes: AttributeTemplate[];
}

export interface SectorDefinition {
  name: string;
  slug: string;
  sector: Sector;
  description: string;
  attributeGroups: { name: string; slug: string }[];
  productTypes: ProductTypeTemplate[];
}

