// ─── ALL SECTORS ────────────────────────────────────────────────

export const allSectors: SectorDefinition[] = [
  electronicsSector,
  fashionSector,
  foodSector,
  industrialSector,
  homeSector,
  beautySector,
];

export function getSectorBySlug(slug: string): SectorDefinition | undefined {
  return allSectors.find((s) => s.slug === slug);
}

export function getProductTypeBySlug(slug: string): ProductTypeTemplate | undefined {
  for (const sector of allSectors) {
    const pt = sector.productTypes.find((t) => t.slug === slug);
    if (pt) return pt;
  }
  return undefined;
}
